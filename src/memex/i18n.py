"""The language of a wiki: folder names, front-matter keys and generated text.

memex itself is written in English. A wiki is written in one language, chosen
when it is created (MEMEX_LANG) and recorded inside the wiki (`.memex/wiki.json`),
so that the server, every host and a rebuilt server all agree on it.

Only two things are localised: what lands in the wiki, and the text assembled
into the agents' prompts. Command output, logs and errors stay in English.

Adding a language takes one `Locale` below, a `prompts/<lang>/` folder and a
`wiki_template/<lang>/AGENTS.md`.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

DEFAULT = "en"
WIKI_FILE = ".memex/wiki.json"

# Front-matter keys that are the same in every language.
K_TYPE, K_DATE, K_SOURCES, K_ALIASES = "type", "date", "sources", "aliases"


@dataclass(frozen=True)
class Locale:
    lang: str
    # Top-level folders, and the decisions sub-folder of a project or topic.
    projects: str
    topics: str
    concepts: str
    journal: str
    decisions: str
    # Front-matter keys.
    k_title: str
    k_summary: str
    k_entities: str
    k_status: str
    k_supersedes: str
    k_superseded_by: str
    k_updated: str
    # Front-matter values, canonical name → name written in the wiki.
    types: dict          # project, topic, decision, concept, synthesis, journal, meta
    statuses: dict       # active, superseded, abandoned
    # Labels written in log.md.
    roles: dict          # archivist, weaver, curator, restore
    kinds: dict          # curator actions: merge, condense, fix, delete, move
    # Heading of the section the weaver may add at the end of a page.
    see_also: str
    strings: dict

    @property
    def content_dirs(self) -> tuple:
        return (self.projects, self.topics, self.concepts)

    def type(self, name: str) -> str:
        return self.types[name]

    def status(self, name: str) -> str:
        return self.statuses[name]

    def t(self, key: str, **values) -> str:
        return self.strings[key].format(**values)


