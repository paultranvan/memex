LOCALES = {EN.lang: EN, FR.lang: FR}
_current = EN


class UnsupportedLanguage(ValueError):
    pass


def get(lang: str) -> Locale:
    key = (lang or DEFAULT).strip().lower()
    if key not in LOCALES:
        raise UnsupportedLanguage(
            f"unsupported wiki language {lang!r} (MEMEX_LANG): choose one of {', '.join(sorted(LOCALES))}"
        )
    return LOCALES[key]


def use(lang: str) -> Locale:
    """Makes `lang` the language of the wiki this process works on."""
    global _current
    _current = get(lang)
    return _current


def current() -> Locale:
    return _current


def detect(root: Path, default: str = "") -> str:
    """The language of the wiki at `root`: what it recorded, else what its folders show, else `default`."""
    root = Path(root)
    try:
        lang = str(json.loads((root / WIKI_FILE).read_text(encoding="utf-8")).get("lang") or "").lower()
        if lang in LOCALES:
            return lang
    except (OSError, ValueError, AttributeError):
        pass
    for candidate in LOCALES.values():
        if candidate.lang != DEFAULT and ((root / candidate.projects).is_dir() or (root / candidate.topics).is_dir()):
            return candidate.lang
    if (root / EN.projects).is_dir() or (root / EN.topics).is_dir():
        return EN.lang
    return get(default).lang if default else DEFAULT


def record(root: Path, lang: str) -> None:
    """Writes the wiki's language into the wiki, where every clone of it can read it."""
    target = Path(root) / WIKI_FILE
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps({"lang": get(lang).lang}) + "\n", encoding="utf-8")


def use_for(root: Path, default: str = "") -> Locale:
    """Detects the language of the wiki at `root` and makes it current."""
    return use(detect(root, default))
