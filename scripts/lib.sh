# Functions shared by the installation scripts. To be sourced, not executed.
# shellcheck shell=bash

say()  { printf '%s\n' "$*"; }
step() { printf '\n→ %s\n' "$*"; }
warn() { printf '  ! %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }

need() {
    command -v "$1" >/dev/null 2>&1 || die "\"$1\" not found: install it, then run this script again"
}

check_python() {
    need python3
    python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 9) else 1)' \
        || die "Python 3.9 or later is required (found: $(python3 --version 2>&1))"
}

# set_kv FILE KEY VALUE — sets or replaces a KEY=VALUE line.
set_kv() {
    local file="$1" key="$2" value="$3" tmp
    case "$value" in *[[:space:]]*) value="\"$value\"" ;; esac
    tmp="$(mktemp)"
    if [ -f "$file" ] && grep -q -E "^(export[[:space:]]+)?${key}=" "$file"; then
        awk -v k="$key" -v v="$value" '
            $0 ~ "^(export[[:space:]]+)?" k "=" && !done { print k "=" v; done = 1; next }
            { print }' "$file" > "$tmp"
    else
        [ -f "$file" ] && cat "$file" > "$tmp"
        printf '%s=%s\n' "$key" "$value" >> "$tmp"
    fi
    cat "$tmp" > "$file"
    rm -f "$tmp"
}

# install_app SOURCE TARGET — copies the Python package (or links it, in development mode).
install_app() {
    local source="$1" target="$2" link="${3:-0}"
    mkdir -p "$(dirname "$target")"
    rm -rf "$target"
    if [ "$link" = "1" ]; then
        ln -s "$source" "$target"
    else
        mkdir -p "$target"
        cp -R "$source/memex" "$target/memex"
        find "$target" -name '__pycache__' -type d -prune -exec rm -rf {} +
    fi
}

# write_wrapper PATH APP_DIR [MODULE_ARGS…] — creates the `memex` command (or `memex-gate`).
write_wrapper() {
    local path="$1" app="$2"; shift 2
    mkdir -p "$(dirname "$path")"
    cat > "$path" <<EOF
#!/bin/sh
# Generated by memex. Run the installer again to update it.
exec env PYTHONPATH="$app\${PYTHONPATH:+:\$PYTHONPATH}" python3 -m memex $* "\$@"
EOF
    chmod 755 "$path"
}

# render TEMPLATE TARGET KEY=VALUE… — replaces each @KEY@ in a template.
render() {
    local template="$1" target="$2"; shift 2
    local content pair key value
    content="$(cat "$template")"
    for pair in "$@"; do
        key="${pair%%=*}"; value="${pair#*=}"
        content="${content//@${key}@/${value}}"
    done
    printf '%s\n' "$content" > "$target"
}
